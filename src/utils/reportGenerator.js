/**
 * Report Generator for Mr. Bingo Screening App
 * 
 * Calls Gemini API to generate a parent-friendly clinical summary
 * from scored game sessions.
 */

const DISCLAIMER = `\n\n⚠️ IMPORTANT DISCLAIMER: This report is generated by an AI system and is NOT a medical diagnosis. It is intended as an informational screening tool only. Please consult a qualified healthcare professional (pediatrician, developmental pediatrician, child psychologist, or neuropsychologist) for formal evaluation and diagnosis.`;

const GEMINI_API_URL = 'https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent';

/**
 * Generate a parent-friendly clinical narrative report.
 * 
 * @param {{ name: string, age: number, grade: string }} childProfile
 * @param {Array<{ gameId: string, scoredResult: object, timestamp: string }>} allGameScores
 * @returns {Promise<string>} - The report text
 */
export async function generateReport(childProfile, allGameScores) {
    // Build a structured summary for the prompt
    const scoreSummary = allGameScores.map((session) => {
        const r = session.scoredResult;
        return `- ${session.gameId} (${r.domain}): Composite ${r.composite}/100, Risk: ${r.riskLevel}, Percentile: ${r.percentile}th
  Sub-scores: ${JSON.stringify(r.subScores)}`;
    }).join('\n');

    const prompt = `You are a child development specialist writing a report for parents. Based on the following screening data for a child, write a clear, compassionate, parent-friendly summary.

CHILD PROFILE:
- Name: ${childProfile.name}
- Age: ${childProfile.age} years
- Grade: ${childProfile.grade || 'Not specified'}

SCREENING RESULTS:
${scoreSummary}

INSTRUCTIONS:
1. Write exactly 3 paragraphs.
2. Paragraph 1: Summarize the child's overall performance across all domains. Mention specific strengths.
3. Paragraph 2: Highlight any areas where the child may benefit from additional support. Be gentle and constructive — avoid alarming language. Reference specific game results where relevant.
4. Paragraph 3: Provide actionable next steps the parent can take, such as consulting a specialist, practicing specific skills at home, or scheduling a formal evaluation if any domain shows "High" risk.
5. Use the child's first name throughout.
6. Keep language at a 6th-grade reading level. Avoid clinical jargon.
7. Do NOT include any diagnosis or diagnostic labels.`;

    // Get API key from Vite env or localStorage fallback
    const apiKey = import.meta.env?.VITE_GEMINI_API_KEY
        || localStorage.getItem('gemini_api_key')
        || '';

    try {
        const response = await fetch(`${GEMINI_API_URL}?key=${apiKey}`, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({
                contents: [
                    {
                        parts: [{ text: prompt }],
                    },
                ],
                generationConfig: {
                    maxOutputTokens: 1024,
                    temperature: 0.7,
                },
            }),
        });

        if (!response.ok) {
            const errText = await response.text();
            console.error('[reportGenerator] Gemini API Error:', response.status, errText);
            return generateFallbackReport(childProfile, allGameScores);
        }

        const data = await response.json();
        const reportText = data.candidates?.[0]?.content?.parts
            ?.map((part) => part.text)
            .join('\n\n') || '';

        if (!reportText) {
            console.warn('[reportGenerator] Empty response from Gemini');
            return generateFallbackReport(childProfile, allGameScores);
        }

        return reportText + DISCLAIMER;
    } catch (error) {
        console.error('[reportGenerator] Fetch error:', error);
        return generateFallbackReport(childProfile, allGameScores);
    }
}

/**
 * Generate a local template report when API is unavailable.
 */
function generateFallbackReport(childProfile, allGameScores) {
    const hasHighRisk = allGameScores.some((s) => s.scoredResult?.riskLevel === 'High');
    const hasModerateRisk = allGameScores.some((s) => s.scoredResult?.riskLevel === 'Moderate');

    const strengths = allGameScores
        .filter(s => s.scoredResult?.riskLevel === 'Low')
        .map(s => s.scoredResult?.domain)
        .filter(Boolean);

    const concerns = allGameScores
        .filter(s => s.scoredResult?.riskLevel !== 'Low')
        .map(s => `${s.scoredResult?.domain} (${s.scoredResult?.riskLevel} risk)`)
        .filter(Boolean);

    let report = `${childProfile.name} completed a series of screening activities across ${allGameScores.length} developmental domains. `;

    if (strengths.length > 0) {
        report += `${childProfile.name} showed age-appropriate performance in ${strengths.join(', ')}. `;
    }

    report += `\n\n`;

    if (concerns.length > 0) {
        report += `Some areas may benefit from additional support or practice: ${concerns.join(', ')}. `;
        report += `These results don't mean there is a problem — they simply highlight areas where targeted activities could help ${childProfile.name} grow.`;
    } else {
        report += `All assessed areas showed development within the expected range for ${childProfile.name}'s age group. Keep up the great work!`;
    }

    report += `\n\n`;

    if (hasHighRisk) {
        report += `We recommend discussing these results with ${childProfile.name}'s pediatrician or a child development specialist for a comprehensive evaluation. Early support can make a meaningful difference.`;
    } else if (hasModerateRisk) {
        report += `Consider practicing related skills at home through games and activities. If you have concerns, a conversation with ${childProfile.name}'s teacher or pediatrician is a good next step.`;
    } else {
        report += `Continue encouraging ${childProfile.name}'s learning through play. Regular check-ins with these screening activities can help track progress over time.`;
    }

    return report + DISCLAIMER;
}
